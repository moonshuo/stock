const byCode = new Map(data.stocks.map((stock) => [stock.code, stock]));
let added = 0;
for (const [primary, code, name, secondary, tertiary, tags, note] of rows) {
  let stock = byCode.get(code);
  if (!stock) { stock = { code, name, primary_sector: primary, classifications: [], product_tags: tags, reason: note }; data.stocks.push(stock); byCode.set(code, stock); }
  stock.name = name;
  stock.product_tags = [...new Set([...(stock.product_tags || []), ...tags])];
  const cls = stock.classifications.find((item) => item.primary_sector === primary && item.secondary_sector === secondary);
  if (cls && cls.tertiary_sectors.includes(tertiary)) continue;
  if (cls) cls.tertiary_sectors = [...new Set([...cls.tertiary_sectors, tertiary])];
  else stock.classifications.push({ primary_sector: primary, secondary_sector: secondary, tertiary_sectors: [tertiary], relevance_score: 1, source_refs: ["业务资料核对"], verification_note: note });
  added += 1;
}
data.stocks.sort((a, b) => a.code.localeCompare(b.code));
await writeFile(file, `${JSON.stringify(data, null, 2)}\n`, "utf8");
console.log(`added ${added} direct-business classifications`);
