const [taxonomy, stockMap] = await Promise.all([
  readFile(taxonomyPath, "utf8").then(JSON.parse),
  readFile(stocksPath, "utf8").then(JSON.parse),
]);

for (const [primaryName, secondarySectors] of Object.entries(sectorDefinitions)) {
  const sector = { name: primaryName, secondary_sectors: secondarySectors };
  const index = taxonomy.sectors.findIndex((item) => item.name === primaryName);
  if (index >= 0) taxonomy.sectors[index] = sector;
  else taxonomy.sectors.push(sector);
}

for (const [primarySector, code, name, secondarySector, tertiarySectors, tags, reason] of assignments) {
  let stock = stockMap.stocks.find((item) => item.code === code);
  if (!stock) {
    stock = { code, name, primary_sector: primarySector, classifications: [], product_tags: [], reason };
    stockMap.stocks.push(stock);
  }
  stock.name ||= name;
  stock.primary_sector ||= primarySector;
  stock.product_tags = [...new Set([...(stock.product_tags || []), ...tags])];
  stock.reason ||= reason;
  let classification = stock.classifications.find(
    (item) => item.primary_sector === primarySector && item.secondary_sector === secondarySector,
  );
  if (!classification) {
    classification = {
      primary_sector: primarySector,
      secondary_sector: secondarySector,
      tertiary_sectors: [],
      relevance_score: 0.9,
      source_refs: ["产业链人工归类"],
      verification_note: reason,
    };
    stock.classifications.push(classification);
  }
  classification.tertiary_sectors = [...new Set([...(classification.tertiary_sectors || []), ...tertiarySectors])];
}

await Promise.all([
  writeFile(taxonomyPath, `${JSON.stringify(taxonomy, null, 2)}\n`, "utf8"),
  writeFile(stocksPath, `${JSON.stringify(stockMap, null, 2)}\n`, "utf8"),
]);

