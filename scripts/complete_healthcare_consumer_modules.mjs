for (const [name, groups] of definitions) {
  const replacement = { name, secondary_sectors: groups.map(([secondary, tertiary]) => ({ name: secondary, tertiary_sectors: tertiary })) };
  const index = taxonomy.sectors.findIndex((sector) => sector.name === name);
  if (index >= 0) taxonomy.sectors[index] = replacement; else taxonomy.sectors.push(replacement);
}
const byCode = new Map(data.stocks.map((stock) => [stock.code, stock]));
let added = 0;
for (const row of rows) {
  let stock = byCode.get(row.code);
  if (!stock) { stock = { code: row.code, name: row.name, primary_sector: row.p, classifications: [], product_tags: [], reason: row.reason }; data.stocks.push(stock); byCode.set(row.code, stock); }
  stock.name = row.name;
  stock.product_tags = [...new Set([...(stock.product_tags || []), ...row.tags])];
  let cls = stock.classifications.find((item) => item.primary_sector === row.p && item.secondary_sector === row.s);
  if (!cls) { cls = { primary_sector: row.p, secondary_sector: row.s, tertiary_sectors: [], relevance_score: 1, source_refs: ["业务资料核对"] }; stock.classifications.push(cls); }
  cls.tertiary_sectors = [...new Set([...(cls.tertiary_sectors || []), ...row.t])];
  cls.relevance_score = 1;
  cls.source_refs = [...new Set([...(cls.source_refs || []), "业务资料核对"])];
  if (!stock.reason || stock.reason === "相关产业链业务") stock.reason = row.reason;
  added += 1;
}
