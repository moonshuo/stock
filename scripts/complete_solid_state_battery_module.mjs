const byCode = new Map(library.stocks.map((stock) => [stock.code, stock]));
for (const [code, name, tertiary, score, reason, tags] of items) {
  let stock = byCode.get(code);
  if (!stock) {
    stock = { code, name, primary_sector: '锂电产业链', classifications: [], product_tags: [], reason: '' };
    library.stocks.push(stock);
    byCode.set(code, stock);
  }
  const exists = stock.classifications.some((c) => c.primary_sector === '锂电产业链' && c.secondary_sector === '固态电池产业链' && c.tertiary_sectors.includes(tertiary));
  if (!exists) stock.classifications.push({ primary_sector: '锂电产业链', secondary_sector: '固态电池产业链', tertiary_sectors: [tertiary], relevance_score: score, source_refs: ['公司公告、年报及主营产品资料核验'] });
  stock.product_tags = [...new Set([...(stock.product_tags || []), ...tags])];
  stock.reason = stock.reason ? `${stock.reason}；${reason}` : reason;
}

