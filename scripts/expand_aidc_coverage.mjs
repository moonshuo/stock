const byCode = new Map(data.stocks.map((item) => [item.code, item]));
for (const [code, name, classifications, product_tags, reason] of stocks) {
  const existing = byCode.get(code);
  if (existing) {
    const keep = (existing.classifications || []).filter((item) => (item.primary_sector || existing.primary_sector) !== P);
    existing.classifications = [...keep, ...classifications];
    existing.product_tags = Array.from(new Set([...(existing.product_tags || []), ...product_tags]));
    if (!existing.reason) existing.reason = reason;
  } else {
    const item = { code, name, primary_sector: P, classifications, product_tags, reason };
    data.stocks.push(item);
    byCode.set(code, item);
  }
}
